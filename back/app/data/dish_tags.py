# 从筛选区里退下来的规范标签。
#
# 【为什么不把规则一起删掉】
# 规则本身是准确的 —— 「年夜饭」「便当」「一人食」打在菜上没毛病，
# 只是精选之后数量太少，撑不起一个可点的分类入口。删规则反而更糟：
# 这些菜会掉进更宽泛的桶里被**错误归类**（「年夜饭」会被「饭」规则吃掉，
# 变成一道"主食"）。
#
# 所以：规则留着（卡片上的分类依然准确），只是不进筛选区。
# `_ordered()` 会把非筛选标签排在核心分类**之后**，
# 所以卡片上优先显示的仍然是那个可点的分类。
RETIRED_TAGS: tuple[str, ...] = (
    "便当", "一人食", "年夜饭", "午餐", "晚餐", "儿童", "创意菜",
    "锅物", "甜品烘焙", "小吃夜宵", "酸甜糖醋", "酱香香料", "丸子",
    "地方菜", "日式", "韩式", "西式",
)

# 扁平化的规范标签集合（用于校验规则是否漏了组）
ALL_CANONICAL_TAGS: tuple[str, ...] = tuple(
    dict.fromkeys(tag for _, tags in TAG_GROUPS for tag in tags)
)

# 规范标签的稳定展示顺序。
# 卡片上的标签按这个顺序排，同一道菜在首页/菜谱页/详情页看到的第一个标签是同一个，
# 不会因为原始 tags_json 的顺序不同而换来换去。
_CANONICAL_ORDER: dict[str, int] = {
    tag: index for index, tag in enumerate(ALL_CANONICAL_TAGS)
}


def canonical_tag(raw: str) -> str | None:
    """把一个原始标签归一成规范标签。归不了（长尾）返回 None。"""
    text = (raw or "").strip()
    if not text:
        return None
    for keywords, canonical in _RULES:
        if any(keyword in text for keyword in keywords):
            return canonical
    return None


def _ordered(values: list[str]) -> list[str]:
    """排标签的显示顺序：筛选区里的核心分类在前，其余（含 RETIRED_TAGS 和长尾）在后。

    这个顺序是有用的：卡片上通常只显示前两个标签，
    排在前面的必须是**可点进筛选区的那个**，否则用户看到一个点不动的分类。
    """
    canonical = sorted(
        (v for v in values if v in _CANONICAL_ORDER), key=_CANONICAL_ORDER.__getitem__
    )
    rest = [v for v in values if v not in _CANONICAL_ORDER]
    return canonical + rest


def canonical_dish_tags(
    raw_tags: list[str] | tuple[str, ...] | None,
    name: str | None = None,
) -> list[str]:
    """把一道菜的原始标签归一化。

    归不了的标签**原样保留** —— 它们仍然是有信息的（「秋日暖汤」这种），
    只是不进筛选分类。这样卡片上不会突然少掉信息。

    `name` 是兜底：实测有 43 道菜 `tags_json` 是空的（「牛肉面」「煎牛排」「腊八粥」
    「兰州拉面」…），这些菜在分类页里一道都点不到。它们的菜名本身信息量足够，
    所以一个规范标签都归不出来时，回头用同一套规则扫一遍菜名。
    """
    result: list[str] = []
    for raw in raw_tags or ():
        text = str(raw).strip()
        if not text:
            continue
        canonical = canonical_tag(text)
        value = text if canonical is None else canonical
        if value not in result:
            result.append(value)

    if name and not any(value in _CANONICAL_ORDER for value in result):
        fallback = canonical_tag(str(name))
        if fallback and fallback not in result:
            result.insert(0, fallback)

    return _ordered(result)


def is_filter_tag(tag: str) -> bool:
    """这个标签能不能进筛选分类（只有规范标签能）。"""
    return tag in ALL_CANONICAL_TAGS
